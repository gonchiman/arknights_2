          <p>同じ条件と抽選番号なら同じ履歴を再現できます。抽選番号は各セルの詳細で確認できます。条件を変更すると、新しい条件で計算した最初の1回の履歴を表示します。{retargetRemainingDrones ? '履歴は100行ずつ表示し、同時刻の記録はページを分けません。各ユニットの攻撃回数や前後の時刻は全履歴を通して数えます。' : '履歴は一斉攻撃100回分ずつ表示します。'}</p>
